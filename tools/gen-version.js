/* Generates app/js/version.js from package.json so the app and the
   installer / PWA share one version number. Run after bumping package.json. */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const out = path.join(ROOT, 'app', 'js', 'version.js');
const body = '/* Generated by tools/gen-version.js from package.json — do not edit. */\n' +
  'window.TIGER_MUSIC_VERSION = ' + JSON.stringify(String(pkg.version || '0.0.0')) + ';\n';

fs.writeFileSync(out, body);
console.log('wrote version ' + pkg.version + ' -> ' + path.relative(ROOT, out));
